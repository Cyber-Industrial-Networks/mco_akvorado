#!/bin/bash
#
# install.sh -- set up Akvorado (NetFlow collector + web console) in Docker Compose on fleet-mon.
#
#   sudo bash /home/yancoal/akvorado/install.sh
#
# Idempotent: safe to re-run. Steps:
#   1. Checks (Docker, Compose, AVX2 for ClickHouse)
#   2. Dedicated 100G LV from ubuntu-vg mounted at /srv/akvorado (ClickHouse data)
#   3. Upstream compose bundle (pinned version) + our config and overrides
#   4. SNMPv3 credentials for the core switches, taken from cellwatch.env
#   5. Docker firewall: NetFlow udp/2055 only from allowed exporters (Docker bypasses ufw)
#   6. nginx HTTPS site on :9444 -> console (fleet-monitor sign-in); ufw allow 9444 from admin subnets;
#      nginx :8090 UE names for Akvorado (Docker subnet only)
#   7. docker compose up
#
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
DEST=/srv/akvorado
VG=ubuntu-vg
LV=akvorado
LV_SIZE_G=100
AKVORADO_VERSION=2026.10.1
BUNDLE_URL=https://github.com/akvorado/akvorado/releases/download/v${AKVORADO_VERSION}/docker-compose-quickstart.tar.gz
CELLWATCH_ENV=/opt/fleet-monitor/cellwatch/cellwatch.env
ADMIN_SOURCES=(10.228.224.0/24 10.228.20.28 10.228.8.0/23)   # same as Graylog :9443

[[ $EUID -eq 0 ]] || { echo "run with sudo"; exit 1; }
step() { echo; echo "==> $*"; }

step "1. Checks"
command -v docker >/dev/null || { echo "Docker not installed"; exit 1; }
systemctl is-active --quiet docker || { echo "Docker not running"; exit 1; }
docker compose version
grep -qw avx2 /proc/cpuinfo || { echo "CPU lacks AVX2: ClickHouse 26.6+ won't run (see docker-compose-local.yml upstream notes)"; exit 1; }

step "2. Storage (${LV_SIZE_G}G LV at $DEST)"
if mountpoint -q "$DEST"; then
  echo "$DEST already mounted"
else
  if ! lvs "$VG/$LV" >/dev/null 2>&1; then
    free_g=$(vgs --noheadings --units g --nosuffix -o vg_free "$VG" | tr -d ' ' | cut -d. -f1)
    echo "free in $VG: ${free_g}G"
    if (( free_g < LV_SIZE_G )); then
      echo "Not enough free space in $VG for a ${LV_SIZE_G}G volume. Adjust LV_SIZE_G and re-run."; exit 1
    fi
    lvcreate -y -L "${LV_SIZE_G}G" -n "$LV" "$VG"
    mkfs.ext4 -q -L akvorado "/dev/$VG/$LV"
  fi
  mkdir -p "$DEST"
  uuid=$(blkid -s UUID -o value "/dev/$VG/$LV")
  grep -q "$uuid" /etc/fstab || echo "UUID=$uuid $DEST ext4 defaults,noatime 0 2" >> /etc/fstab
  systemctl daemon-reload
  mount "$DEST"
fi
df -h "$DEST"

step "3. Compose bundle v${AKVORADO_VERSION} + our config"
if [[ "$(cat $DEST/.bundle-version 2>/dev/null)" != "$AKVORADO_VERSION" ]]; then
  tmp=$(mktemp -d)
  curl -fsSL "$BUNDLE_URL" -o "$tmp/bundle.tgz"
  tar -xzf "$tmp/bundle.tgz" -C "$tmp"
  [[ -f $tmp/docker/docker-compose.yml ]] || { echo "unexpected bundle layout"; ls -R "$tmp" | head; exit 1; }
  rm -rf "$DEST/docker"
  mv "$tmp/docker" "$DEST/docker"
  echo "$AKVORADO_VERSION" > "$DEST/.bundle-version"
  rm -rf "$tmp"
  echo "bundle unpacked to $DEST/docker"
else
  echo "bundle v$AKVORADO_VERSION already in place"
fi
# Our files win over the bundle's (upstream config/ is not used at all).
install -m 644 "$SRC/docker-compose-local.yml" "$DEST/docker/docker-compose-local.yml"
install -m 644 "$SRC/env" "$DEST/.env"
mkdir -p "$DEST/config"
install -m 644 "$SRC"/config/{akvorado,inlet,outlet,console}.yaml "$DEST/config/"
mkdir -p "$DEST/data/clickhouse"
chown 101:101 "$DEST/data/clickhouse"   # clickhouse image user

step "4. SNMPv3 credentials (from $CELLWATCH_ENV, CORE_SNMP_*)"
# Akvorado reads interface names/descriptions from each exporter over SNMP.
# Same user cellwatch already polls the core switches with. Written root-only, never printed.
umask 077
python3 - "$CELLWATCH_ENV" "$DEST/config/snmp-credentials.yaml" <<'PY'
import json, sys
env = {}
for line in open(sys.argv[1]):
    line = line.strip()
    if not line or line.startswith("#") or "=" not in line:
        continue
    k, v = line.split("=", 1)
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        v = v[1:-1]
    env[k.strip()] = v
need = ["CORE_SNMP_USER", "CORE_SNMP_AUTH_PASS", "CORE_SNMP_PRIV_PASS"]
missing = [k for k in need if not env.get(k)]
if missing:
    sys.exit(f"missing in cellwatch.env: {', '.join(missing)}")
auth = env.get("CORE_SNMP_AUTH_PROTO", "SHA").upper()
priv = {"AES128": "AES"}.get(env.get("CORE_SNMP_PRIV_PROTO", "AES128").upper(),
                             env.get("CORE_SNMP_PRIV_PROTO", "AES128").upper())
creds = {
    "user-name": env["CORE_SNMP_USER"],
    "authentication-protocol": auth,
    "authentication-passphrase": env["CORE_SNMP_AUTH_PASS"],
    "privacy-protocol": priv,
    "privacy-passphrase": env["CORE_SNMP_PRIV_PASS"],
}
with open(sys.argv[2], "w") as f:
    f.write("# Generated by install.sh from cellwatch.env (CORE_SNMP_*). Do not edit; re-run install.sh.\n")
    f.write("10.228.224.0/24:\n")
    for k, v in creds.items():
        f.write(f"  {k}: {json.dumps(v)}\n")   # JSON strings are valid YAML scalars
print(f"wrote {sys.argv[2]} (auth {auth}, priv {priv})")
PY
umask 022
chmod 600 "$DEST/config/snmp-credentials.yaml"

step "5. NetFlow firewall (Docker bypasses ufw)"
install -m 755 "$SRC/akvorado-docker-firewall.sh" /usr/local/sbin/akvorado-docker-firewall.sh
cat > /etc/systemd/system/akvorado-docker-firewall.service <<'EOF'
[Unit]
Description=Restrict Docker-published NetFlow port 2055 to allowed exporters
After=docker.service
PartOf=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/akvorado-docker-firewall.sh

[Install]
WantedBy=docker.service
EOF
systemctl daemon-reload
systemctl enable akvorado-docker-firewall.service
systemctl restart akvorado-docker-firewall.service

step "6. nginx :9444 (fleet-monitor sign-in) + ufw"
install -m 644 "$SRC/nginx-akvorado.conf" /etc/nginx/sites-available/akvorado
ln -sf /etc/nginx/sites-available/akvorado /etc/nginx/sites-enabled/akvorado
nginx -t
systemctl reload nginx
for s in "${ADMIN_SOURCES[@]}"; do ufw allow from "$s" to any port 9444 proto tcp comment 'akvorado web'; done
# Akvorado outlet container -> nginx :8090 (UE names from fleet-monitor). Docker subnet from upstream compose.
ufw allow from 247.16.14.0/24 to any port 8090 proto tcp comment 'akvorado -> fleet-monitor UE names'

step "7. Start Akvorado"
cd "$DEST"
docker compose config -q
docker compose pull -q
docker compose up -d --wait --wait-timeout 300
docker compose ps

echo
echo "Akvorado is up:  https://10.231.137.100:9444/   (fleet-monitor sign-in)"
echo "NetFlow in:      udp/2055 on 10.231.137.100, allowed from: $(grep ^ALLOWED /usr/local/sbin/akvorado-docker-firewall.sh)"
iptables -S AKVORADO-FLOW
ufw status | grep -E '9444|8090|Status' || true
